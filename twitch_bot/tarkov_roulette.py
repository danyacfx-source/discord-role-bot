class TarkovRoulette:
    def __init__(self):
        self._cooldowns = {}

    def _check_cooldown(self, author, name, seconds):
        key = (name, author.name.lower())
        now = time.time()
        last = self._cooldowns.get(key, 0)
        if now - last < seconds:
            return False
        self._cooldowns[key] = now
        return True

    def _random_item(self):
        return random.choice(ITEMS)

    def loadout(self):
        m = random.choice(MAPS)
        weapon = random.choice(WEAPONS)
        ammo = random.choice(AMMO)
        helm = random.choice(HELMETS)
        armor = random.choice(ARMORS)
        rig = random.choice(RIGS)
        pack = random.choice(BACKPACKS)
        ears = random.choice(HEADSETS)
        meds = random.choice(MEDS)
        nades = random.choice(GRENADES)
        return (
            f"🎒 Рандом на {m}:\n"
            f"🔫 Оружие: **{weapon}** ({ammo})\n"
            f"🪖 Шлем: {helm}\n"
            f"🦺 Броня: {armor}\n"
            f"🎽 Разгрузка: {rig}\n"
            f"🎒 Рюкзак: {pack}\n"
            f"🎧 Наушники: {ears}\n"
            f"💊 Медикаменты: {meds}\n"
            f"💣 Гранаты: {nades}"
        )

    def allergy(self):
        allergen = random.choice(ALLERGENS)
        return f"🤧 Аллергия в этом рейде: нельзя использовать **{allergen}**!"

    def raid_quest(self):
        mode = random.choice(["item", "kill", "boss"])
        m = random.choice(MAPS)
        if mode == "item":
            action = random.choice(ACTIONS)
            item = self._random_item()
            return f"🗺️ Рейд-квест на {m}: {action} **{item}**"
        if mode == "boss":
            boss = random.choice(BOSSES)
            return f"🗺️ Рейд-квест на {m}: убить **{boss}** и выйти живым"
        task = random.choice(KILL_TASKS)
        return f"🗺️ Рейд-квест на {m}: {task}"


roulette = TarkovRoulette()
